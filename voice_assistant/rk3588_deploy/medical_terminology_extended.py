    # ==================== 类方法 ====================
    
    @classmethod
    def get_all_symptoms(cls):
        """获取所有症状"""
        all_symptoms = {}
        for category in [cls.GENERAL_SYMPTOMS, cls.RESPIRATORY_SYMPTOMS, 
                        cls.DIGESTIVE_SYMPTOMS, cls.CARDIOVASCULAR_SYMPTOMS,
                        cls.NEUROLOGICAL_SYMPTOMS, cls.PSYCHIATRIC_SYMPTOMS,
                        cls.URINARY_SYMPTOMS, cls.DERMATOLOGICAL_SYMPTOMS,
                        cls.ENT_SYMPTOMS, cls.GYNECOLOGICAL_SYMPTOMS,
                        cls.PEDIATRIC_SYMPTOMS]:
            all_symptoms.update(category)
        return all_symptoms
    
    @classmethod
    def get_all_diseases(cls):
        """获取所有疾病"""
        all_diseases = {}
        for category in [cls.INTERNAL_MEDICINE_DISEASES, cls.SURGICAL_DISEASES,
                        cls.OBSTETRICS_GYNECOLOGY_DISEASES, cls.PEDIATRIC_DISEASES,
                        cls.DERMATOLOGY_DISEASES, cls.ENT_DISEASES,
                        cls.PSYCHIATRIC_DISEASES, cls.INFECTIOUS_DISEASES,
                        cls.ONCOLOGY_DISEASES]:
            all_diseases.update(category)
        return all_diseases
    
    @classmethod
    def get_all_terms_flat(cls):
        """获取所有术语的扁平列表（用于快速匹配）"""
        all_terms = set()
        
        # 症状
        for synonyms in cls.get_all_symptoms().values():
            all_terms.update(synonyms)
        
        # 疾病
        for synonyms in cls.get_all_diseases().values():
            all_terms.update(synonyms)
        
        # 药物
        for drugs in cls.COMMON_DRUGS.values():
            all_terms.update(drugs)
        
        # 检查
        for tests in cls.LAB_TESTS.values():
            all_terms.update(tests)
        
        # 科室关键词
        for keywords in cls.DEPARTMENT_MAPPING.values():
            all_terms.update(keywords)
        
        return all_terms
    
    @classmethod
    def predict_department(cls, query: str) -> tuple:
        """
        预测查询所属科室（增强版）
        返回: (预测科室, 检测到的术语列表, 置信度)
        """
        query_lower = query.lower()
        scores = {}
        detected_terms = []
        
        for dept, keywords in cls.DEPARTMENT_MAPPING.items():
            score = 0
            dept_terms = []
            
            for keyword in keywords:
                # 精确匹配
                if keyword in query_lower:
                    score += len(keyword) * 10
                    dept_terms.append(keyword)
                    continue
                
                # 同义词匹配 - 在症状中查找
                for term, synonyms in cls.get_all_symptoms().items():
                    if keyword == term or keyword in synonyms:
                        for syn in synonyms:
                            if syn in query_lower:
                                score += len(syn) * 5
                                dept_terms.append(f"{term}({syn})")
                                break
                
                # 同义词匹配 - 在疾病中查找
                for disease, synonyms in cls.get_all_diseases().items():
                    if keyword == disease or keyword in synonyms:
                        for syn in synonyms:
                            if syn in query_lower:
                                score += len(syn) * 8  # 疾病权重更高
                                dept_terms.append(f"{disease}({syn})")
                                break
            
            if score > 0:
                scores[dept] = score
                if dept not in [t.split('(')[0] for t in detected_terms]:
                    detected_terms.extend(dept_terms)
        
        # 去重检测到的术语
        detected_terms = list(set(detected_terms))
        
        if scores:
            best_dept = max(scores, key=scores.get)
            confidence = scores[best_dept] / sum(scores.values()) if sum(scores.values()) > 0 else 0
            return best_dept, detected_terms, confidence
        
        return None, [], 0
    
    @classmethod
    def check_antonym_conflict(cls, query: str, result_text: str) -> tuple:
        """
        检查查询和结果是否存在反义词冲突
        返回: (是否有冲突, 冲突词对, 建议)
        """
        query_lower = query.lower()
        result_lower = result_text.lower()
        
        for word1, word2 in cls.ANTONYM_PAIRS:
            # 查询包含词1，结果包含词2
            if word1 in query_lower and word2 in result_lower:
                return True, (word1, word2), f"查询'{word1}'与结果'{word2}'可能存在反义冲突，请核实"
            
            # 查询包含词2，结果包含词1
            if word2 in query_lower and word1 in result_lower:
                return True, (word2, word1), f"查询'{word2}'与结果'{word1}'可能存在反义冲突，请核实"
        
        return False, None, None
    
    @classmethod
    def validate_result(cls, query: str, result_dept: str, result_title: str) -> dict:
        """
        验证检索结果的医学合理性
        """
        validation = {
            'is_valid': True,
            'warnings': [],
            'suggestions': []
        }
        
        # 1. 检查反义词冲突
        has_conflict, conflict_pair, suggestion = cls.check_antonym_conflict(query, result_title)
        if has_conflict:
            validation['warnings'].append(suggestion)
            validation['is_valid'] = False
        
        # 2. 预测查询科室，检查是否匹配
        predicted_dept, terms, confidence = cls.predict_department(query)
        if predicted_dept and predicted_dept != result_dept:
            validation['warnings'].append(
                f"科室不匹配：查询预测为'{predicted_dept}'，但结果为'{result_dept}'"
            )
        
        # 3. 检查术语完整性
        if not terms:
            validation['suggestions'].append("未检测到标准医学术语，建议扩展查询词")
        
        return validation


