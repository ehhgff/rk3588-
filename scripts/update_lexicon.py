def generate_pinyin(text):
    """生成带声调的拼音"""
    return ' '.join([p[0] for p in pinyin(text, style=Style.TONE3)])


def main():
    # 读取现有词典
    existing_terms = set()
    with open(LEXICON_PATH, 'r', encoding='utf-8') as f:
        for line in f:
            if line.strip() and not line.startswith('#'):
                term = line.split()[0]
                existing_terms.add(term)

    # 添加新词汇
    new_entries = []
    for term in MEDICAL_TERMS:
        if term not in existing_terms:
            pinyin_str = generate_pinyin(term)
            new_entries.append(f"{term} {pinyin_str}\n")

    # 追加到词典
    if new_entries:
        with open(LEXICON_PATH, 'a', encoding='utf-8') as f:
            f.write("\n# 新增医疗词汇\n")
            f.writelines(new_entries)
        print(f"Added {len(new_entries)} new medical terms to lexicon")
    else:
        print("No new medical terms to add")


if __name__ == "__main__":
    main()